import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const root = new URL("../../../", import.meta.url);
const sourcePath = new URL("docs/architecture/protocol/core.schema.json", root);
const source = await readFile(sourcePath, "utf8");
const doc = JSON.parse(source);
function type(schema) {
  if (schema.$ref) return schema.$ref.split("/").at(-1);
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (schema.oneOf || schema.anyOf)
    return `(${(schema.oneOf ?? schema.anyOf).map(type).join(" | ")})`;
  if (schema.type === "array") return `Array<${type(schema.items ?? {})}>`;
  if (schema.type === "object" && schema.properties)
    return `{\n${Object.entries(schema.properties)
      .map(
        ([key, value]) =>
          `  ${JSON.stringify(key)}${schema.required?.includes(key) ? "" : "?"}: ${type(value)};`,
      )
      .join("\n")}\n}`;
  if (schema.type === "object") return "Record<string, JSONValue>";
  if (schema.type === "string") return "string";
  if (schema.type === "integer" || schema.type === "number") return "number";
  if (schema.type === "boolean") return "boolean";
  if (schema.type === "null") return "null";
  return "JSONValue";
}
const hash = `sha256:${createHash("sha256").update(source).digest("hex")}`;
const content = [
  "// Generated by sdk/ts/scripts/generate-contracts.mjs from docs/architecture/protocol/core.schema.json. DO NOT EDIT.",
  'import type { JSONValue } from "./json";',
  `export const CORE_SCHEMA_DIGEST = ${JSON.stringify(hash)};`,
  `export const CORE_SCHEMA = ${JSON.stringify(doc)} as const;`,
  ...Object.entries(doc.$defs).map(
    ([name, schema]) =>
      `export type ${name === "Command" ? "CoreCommand" : name} = ${type(schema)};`,
  ),
  "",
].join("\n");
const output = new URL("sdk/ts/src/contracts.gen.ts", root);
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8")) !== content) throw new Error("generated TS contracts drift");
  process.stdout.write("TS contracts match single source\n");
} else {
  await writeFile(output, content);
  process.stdout.write("TS contracts generated\n");
}
